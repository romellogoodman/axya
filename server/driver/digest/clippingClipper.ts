function getLowermostRec(outRec1: OutRec, outRec2: OutRec): OutRec {
  // work out which polygon fragment has the correct hole state ...
  if (!outRec1.BottomPt) outRec1.BottomPt = getBottomPt(outRec1.Pts as OutPt);
  if (!outRec2.BottomPt) outRec2.BottomPt = getBottomPt(outRec2.Pts as OutPt);
  const outPt1 = outRec1.BottomPt;
  const outPt2 = outRec2.BottomPt;
  if (outPt1.Pt.Y > outPt2.Pt.Y) return outRec1;
  else if (outPt1.Pt.Y < outPt2.Pt.Y) return outRec2;
  else if (outPt1.Pt.X < outPt2.Pt.X) return outRec1;
  else if (outPt1.Pt.X > outPt2.Pt.X) return outRec2;
  else if (outPt1.Next === outPt1) return outRec2;
  else if (outPt2.Next === outPt2) return outRec1;
  else if (firstIsBottomPt(outPt1, outPt2)) return outRec1;
  else return outRec2;
}

function isMaxima(e: TEdge | null, Y: number): boolean {
  return !!e && e.Top.Y === Y && !e.NextInLML;
}

function isIntermediate(e: TEdge, Y: number): boolean {
  return e.Top.Y === Y && !!e.NextInLML;
}

function getMaximaPair(e: TEdge): TEdge | null {
  if (ptEq(e.Next.Top, e.Top) && !e.Next.NextInLML) return e.Next;
  else if (ptEq(e.Prev.Top, e.Top) && !e.Prev.NextInLML) return e.Prev;
  else return null;
}

function getMaximaPairEx(e: TEdge): TEdge | null {
  // as GetMaximaPair() but returns 0 if MaxPair isn't in AEL (unless it's horizontal)
  const result = getMaximaPair(e);
  if (
    result &&
    (result.OutIdx === SKIP ||
      (result.NextInAEL === result.PrevInAEL && !isHorizontal(result)))
  )
    return null;
  return result;
}

function getNextInAEL(e: TEdge, dir: number): TEdge | null {
  return dir === D_LEFT_TO_RIGHT ? e.NextInAEL : e.PrevInAEL;
}

/** GetHorzDirection: [Dir, Left, Right]. */
function getHorzDirection(horzEdge: TEdge): [number, number, number] {
  if (horzEdge.Bot.X < horzEdge.Top.X)
    return [D_LEFT_TO_RIGHT, horzEdge.Bot.X, horzEdge.Top.X];
  return [D_RIGHT_TO_LEFT, horzEdge.Top.X, horzEdge.Bot.X];
}

