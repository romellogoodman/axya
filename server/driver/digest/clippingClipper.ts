// Exact fused multiply-add

const f64 = new Float64Array(1);
const u64 = new BigUint64Array(f64.buffer);
const MANT_MASK = (1n << 52n) - 1n;

/** x = m * 2^e with m a (signed) integer; x finite and nonzero. */
function decompose(x: number): [bigint, number] {
  f64[0] = x;
  const bits = u64[0];
  const biased = Number((bits >> 52n) & 0x7ffn);
  let m = bits & MANT_MASK;
  let e: number;
  if (biased === 0) {
    e = -1074;
  } else {
    m |= 1n << 52n;
    e = biased - 1075;
  }
  return [bits >> 63n ? -m : m, e];
}

/** The double nearest m * 2^e (ties to even), for a normal result. */
function toDouble(m: bigint, e: number): number {
  const neg = m < 0n;
  let mag = neg ? -m : m;
  const extra = mag.toString(2).length - 64;
  if (extra > 0) {
    // Keep 64 bits plus a sticky bit: Number() then rounds as the full value would.
    const lost = mag & ((1n << BigInt(extra)) - 1n);
    mag = (mag >> BigInt(extra)) | (lost ? 1n : 0n);
    e += extra;
  }
  let r = Number(mag);
  // Scaling by a power of two is exact while the result stays normal.
  while (e > 0) {
    const s = Math.min(e, 1000);
    r *= 2 ** s;
    e -= s;
  }
  while (e < 0) {
    const s = Math.min(-e, 1000);
    r /= 2 ** s;
    e += s;
  }
  return neg ? -r : r;
}

/** a*b + c with a single rounding, as arm64's fmadd computes it. */
export function fma(a: number, b: number, c: number): number {
  if (!Number.isFinite(a) || !Number.isFinite(b) || !Number.isFinite(c))
    return a * b + c;
  // An exactly representable product rounds only once anyway.
  if (a === 0 || b === 0) return a * b + c;
  if (c === 0) return a * b;
  const [ma, ea] = decompose(a);
  const [mb, eb] = decompose(b);
  const [mc, ec] = decompose(c);
  const ep = ea + eb;
  const e = Math.min(ep, ec);
  const sum = ((ma * mb) << BigInt(ep - e)) + (mc << BigInt(ec - e));
  if (sum === 0n) return 0;
  return toDouble(sum, e);
}

