function e2InsertsBeforeE1(e1: TEdge, e2: TEdge): boolean {
  if (e2.Curr.X === e1.Curr.X) {
    if (e2.Top.Y > e1.Top.Y) return e2.Top.X < topX(e1, e2.Top.Y);
    else return e1.Top.X > topX(e2, e1.Top.Y);
  } else return e2.Curr.X < e1.Curr.X;
}

/** GetOverlap: [overlaps, Left, Right]. */
function getOverlap(
  a1: number,
  a2: number,
  b1: number,
  b2: number
): [boolean, number, number] {
  let left: number;
  let right: number;
  if (a1 < a2) {
    if (b1 < b2) {
      left = Math.max(a1, b1);
      right = Math.min(a2, b2);
    } else {
      left = Math.max(a1, b2);
      right = Math.min(a2, b1);
    }
  } else {
    if (b1 < b2) {
      left = Math.max(a2, b1);
      right = Math.min(a1, b2);
    } else {
      left = Math.max(a2, b2);
      right = Math.min(a1, b1);
    }
  }
  return [left < right, left, right];
}

function updateOutPtIdxs(outrec: OutRec): void {
  let op = outrec.Pts as OutPt;
  do {
    op.Idx = outrec.Idx;
    op = op.Prev;
  } while (op !== outrec.Pts);
}

function dupOutPt(outPt: OutPt, insertAfter: boolean): OutPt {
  const result = new OutPt();
  result.Pt = copyPt(outPt.Pt);
  result.Idx = outPt.Idx;
  if (insertAfter) {
    result.Next = outPt.Next;
    result.Prev = outPt;
    outPt.Next.Prev = result;
    outPt.Next = result;
  } else {
    result.Prev = outPt.Prev;
    result.Next = outPt;
    outPt.Prev.Next = result;
    outPt.Prev = result;
  }
  return result;
}

function joinHorz(
  op1: OutPt,
  op1b: OutPt,
  op2: OutPt,
  op2b: OutPt,
  Pt: IntPoint,
  discardLeft: boolean
): boolean {
  const dir1 = op1.Pt.X > op1b.Pt.X ? D_RIGHT_TO_LEFT : D_LEFT_TO_RIGHT;
  const dir2 = op2.Pt.X > op2b.Pt.X ? D_RIGHT_TO_LEFT : D_LEFT_TO_RIGHT;
  if (dir1 === dir2) return false;

  if (dir1 === D_LEFT_TO_RIGHT) {
    while (
      op1.Next.Pt.X <= Pt.X &&
      op1.Next.Pt.X >= op1.Pt.X &&
      op1.Next.Pt.Y === Pt.Y
    )
      op1 = op1.Next;
    if (discardLeft && op1.Pt.X !== Pt.X) op1 = op1.Next;
    op1b = dupOutPt(op1, !discardLeft);
    if (!ptEq(op1b.Pt, Pt)) {
      op1 = op1b;
      op1.Pt = copyPt(Pt);
      op1b = dupOutPt(op1, !discardLeft);
    }
  } else {
    while (
      op1.Next.Pt.X >= Pt.X &&
      op1.Next.Pt.X <= op1.Pt.X &&
      op1.Next.Pt.Y === Pt.Y
    )
      op1 = op1.Next;
    if (!discardLeft && op1.Pt.X !== Pt.X) op1 = op1.Next;
    op1b = dupOutPt(op1, discardLeft);
    if (!ptEq(op1b.Pt, Pt)) {
      op1 = op1b;
      op1.Pt = copyPt(Pt);
      op1b = dupOutPt(op1, discardLeft);
    }
  }

  if (dir2 === D_LEFT_TO_RIGHT) {
    while (
      op2.Next.Pt.X <= Pt.X &&
      op2.Next.Pt.X >= op2.Pt.X &&
      op2.Next.Pt.Y === Pt.Y
    )
      op2 = op2.Next;
    if (discardLeft && op2.Pt.X !== Pt.X) op2 = op2.Next;
    op2b = dupOutPt(op2, !discardLeft);
    if (!ptEq(op2b.Pt, Pt)) {
      op2 = op2b;
      op2.Pt = copyPt(Pt);
      op2b = dupOutPt(op2, !discardLeft);
    }
  } else {
    while (
      op2.Next.Pt.X >= Pt.X &&
      op2.Next.Pt.X <= op2.Pt.X &&
      op2.Next.Pt.Y === Pt.Y
    )
      op2 = op2.Next;
    if (!discardLeft && op2.Pt.X !== Pt.X) op2 = op2.Next;
    op2b = dupOutPt(op2, discardLeft);
    if (!ptEq(op2b.Pt, Pt)) {
      op2 = op2b;
      op2.Pt = copyPt(Pt);
      op2b = dupOutPt(op2, discardLeft);
    }
  }

  if ((dir1 === D_LEFT_TO_RIGHT) === discardLeft) {
    op1.Prev = op2;
    op2.Next = op1;
    op1b.Next = op2b;
    op2b.Prev = op1b;
  } else {
    op1.Next = op2;
    op2.Prev = op1;
    op1b.Prev = op2b;
    op2b.Next = op1b;
  }
  return true;
}

function parseFirstLeft(firstLeft: OutRec | null): OutRec | null {
  while (firstLeft && !firstLeft.Pts) firstLeft = firstLeft.FirstLeft;
  return firstLeft;
}

function pointCount(pts: OutPt | null): number {
  if (!pts) return 0;
  let result = 0;
  let p = pts;
  do {
    result++;
    p = p.Next;
  } while (p !== pts);
  return result;
}

/** std::priority_queue<cInt>: a binary max-heap of scanbeam Ys. */
class Scanbeam {
  private h: number[] = [];

  get empty(): boolean {
    return this.h.length === 0;
  }

  top(): number {
    return this.h[0];
  }

  push(v: number): void {
    const h = this.h;
    let i = h.push(v) - 1;
    while (i > 0) {
      const parent = (i - 1) >> 1;
      if (h[parent] >= h[i]) break;
      [h[parent], h[i]] = [h[i], h[parent]];
      i = parent;
    }
  }

  pop(): void {
    const h = this.h;
    const last = h.pop() as number;
    if (h.length === 0) return;
    h[0] = last;
    let i = 0;
    for (;;) {
      const l = 2 * i + 1;
      const r = l + 1;
      let m = i;
      if (l < h.length && h[l] > h[m]) m = l;
      if (r < h.length && h[r] > h[m]) m = r;
      if (m === i) break;
      [h[m], h[i]] = [h[i], h[m]];
      i = m;
    }
  }
}

