/** DistanceSqrd (clipper.cpp:4320-4325); fused. */
export function distanceSqrd(pt1: IntPoint, pt2: IntPoint): number {
  const dx = pt1.X - pt2.X;
  const dy = pt1.Y - pt2.Y;
  return fma(dx, dx, dy * dy);
}

/** DistanceFromLineSqrd (clipper.cpp:4328-4342); fused as clang did. */
function distanceFromLineSqrd(
  p: IntPoint,
  ln1: IntPoint,
  ln2: IntPoint
): number {
  const A = ln1.Y - ln2.Y;
  const B = ln2.X - ln1.X;
  let C = fma(A, ln1.X, B * ln1.Y);
  C = fma(A, p.X, B * p.Y) - C;
  return (C * C) / fma(A, A, B * B);
}

function slopesNearCollinear(
  pt1: IntPoint,
  pt2: IntPoint,
  pt3: IntPoint,
  distSqrd: number
): boolean {
  // this function is more accurate when the point that's geometrically
  // between the other 2 points is the one that's tested for distance.
  // ie makes it more likely to pick up 'spikes' ...
  if (abs(pt1.X - pt2.X) > abs(pt1.Y - pt2.Y)) {
    if (pt1.X > pt2.X === pt1.X < pt3.X)
      return distanceFromLineSqrd(pt1, pt2, pt3) < distSqrd;
    else if (pt2.X > pt1.X === pt2.X < pt3.X)
      return distanceFromLineSqrd(pt2, pt1, pt3) < distSqrd;
    else return distanceFromLineSqrd(pt3, pt1, pt2) < distSqrd;
  } else {
    if (pt1.Y > pt2.Y === pt1.Y < pt3.Y)
      return distanceFromLineSqrd(pt1, pt2, pt3) < distSqrd;
    else if (pt2.Y > pt1.Y === pt2.Y < pt3.Y)
      return distanceFromLineSqrd(pt2, pt1, pt3) < distSqrd;
    else return distanceFromLineSqrd(pt3, pt1, pt2) < distSqrd;
  }
}

/** PointsAreClose (clipper.cpp:4372-4377); fused. */
function pointsAreClose(
  pt1: IntPoint,
  pt2: IntPoint,
  distSqrd: number
): boolean {
  const dx = pt1.X - pt2.X;
  const dy = pt1.Y - pt2.Y;
  return fma(dx, dx, dy * dy) <= distSqrd;
}

function excludeOp(op: OutPt): OutPt {
  const result = op.Prev;
  result.Next = op.Next;
  op.Next.Prev = result;
  result.Idx = 0;
  return result;
}

/** CleanPolygon(in_poly, out_poly, distance) (clipper.cpp:4390-4440). */
export function CleanPolygon(inPoly: IntPoint[], distance = 1.415): IntPoint[] {
  // distance = proximity in units/pixels below which vertices
  // will be stripped. Default ~= sqrt(2).
  let size = inPoly.length;
  if (size === 0) return [];

  const outPts: OutPt[] = [];
  for (let i = 0; i < size; ++i) outPts.push(new OutPt());
  for (let i = 0; i < size; ++i) {
    outPts[i].Pt = copyPt(inPoly[i]);
    outPts[i].Next = outPts[(i + 1) % size];
    outPts[i].Next.Prev = outPts[i];
    outPts[i].Idx = 0;
  }

  const distSqrd = distance * distance;
  let op = outPts[0];
  while (op.Idx === 0 && op.Next !== op.Prev) {
    if (pointsAreClose(op.Pt, op.Prev.Pt, distSqrd)) {
      op = excludeOp(op);
      size--;
    } else if (pointsAreClose(op.Prev.Pt, op.Next.Pt, distSqrd)) {
      excludeOp(op.Next);
      op = excludeOp(op);
      size -= 2;
    } else if (slopesNearCollinear(op.Prev.Pt, op.Pt, op.Next.Pt, distSqrd)) {
      op = excludeOp(op);
      size--;
    } else {
      op.Idx = 1;
      op = op.Next;
    }
  }

  if (size < 3) size = 0;
  const out: IntPoint[] = [];
  for (let i = 0; i < size; ++i) {
    out.push(copyPt(op.Pt));
    op = op.Next;
  }
  return out;
}

