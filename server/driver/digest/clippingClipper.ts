function initEdge2(e: TEdge, polyTyp: number): void {
  if (e.Curr.Y >= e.Next.Curr.Y) {
    e.Bot = copyPt(e.Curr);
    e.Top = copyPt(e.Next.Curr);
  } else {
    e.Top = copyPt(e.Curr);
    e.Bot = copyPt(e.Next.Curr);
  }
  setDx(e);
  e.PolyTyp = polyTyp;
}

function removeEdge(e: TEdge): TEdge {
  // removes e from double_linked_list (but without removing from memory)
  e.Prev.Next = e.Next;
  e.Next.Prev = e.Prev;
  const result = e.Next;
  e.Prev = null as unknown as TEdge; // flag as removed (see ClipperBase.Clear)
  return result;
}

function reverseHorizontal(e: TEdge): void {
  const t = e.Top.X;
  e.Top.X = e.Bot.X;
  e.Bot.X = t;
}

function firstIsBottomPt(btmPt1: OutPt, btmPt2: OutPt): boolean {
  let p = btmPt1.Prev;
  while (ptEq(p.Pt, btmPt1.Pt) && p !== btmPt1) p = p.Prev;
  const dx1p = Math.abs(getDx(btmPt1.Pt, p.Pt));
  p = btmPt1.Next;
  while (ptEq(p.Pt, btmPt1.Pt) && p !== btmPt1) p = p.Next;
  const dx1n = Math.abs(getDx(btmPt1.Pt, p.Pt));

  p = btmPt2.Prev;
  while (ptEq(p.Pt, btmPt2.Pt) && p !== btmPt2) p = p.Prev;
  const dx2p = Math.abs(getDx(btmPt2.Pt, p.Pt));
  p = btmPt2.Next;
  while (ptEq(p.Pt, btmPt2.Pt) && p !== btmPt2) p = p.Next;
  const dx2n = Math.abs(getDx(btmPt2.Pt, p.Pt));

  if (
    Math.max(dx1p, dx1n) === Math.max(dx2p, dx2n) &&
    Math.min(dx1p, dx1n) === Math.min(dx2p, dx2n)
  )
    return areaOutPt(btmPt1) > 0; // if otherwise identical use orientation
  return (dx1p >= dx2p && dx1p >= dx2n) || (dx1n >= dx2p && dx1n >= dx2n);
}

function getBottomPt(pp: OutPt): OutPt {
  let dups: OutPt | null = null;
  let p = pp.Next;
  while (p !== pp) {
    if (p.Pt.Y > pp.Pt.Y) {
      pp = p;
      dups = null;
    } else if (p.Pt.Y === pp.Pt.Y && p.Pt.X <= pp.Pt.X) {
      if (p.Pt.X < pp.Pt.X) {
        dups = null;
        pp = p;
      } else {
        if (p.Next !== pp && p.Prev !== pp) dups = p;
      }
    }
    p = p.Next;
  }
  if (dups) {
    // there appears to be at least 2 vertices at BottomPt so ...
    while (dups !== p) {
      if (!firstIsBottomPt(p, dups)) pp = dups;
      dups = dups.Next;
      while (!ptEq(dups.Pt, pp.Pt)) dups = dups.Next;
    }
  }
  return pp;
}

function horzSegmentsOverlap(
  seg1a: number,
  seg1b: number,
  seg2a: number,
  seg2b: number
): boolean {
  if (seg1a > seg1b) [seg1a, seg1b] = [seg1b, seg1a];
  if (seg2a > seg2b) [seg2a, seg2b] = [seg2b, seg2a];
  return seg1a < seg2b && seg2a < seg1b;
}

function rangeTest(p: IntPoint): void {
  // Clipper's loRange/hiRange choice only selects how SlopesEqual multiplies;
  // here every product is exact, so only the (narrower) hard limit remains.
  if (p.X > HI_RANGE || p.Y > HI_RANGE || -p.X > HI_RANGE || -p.Y > HI_RANGE)
    throw new ClipperRangeError();
}

function findNextLocMin(E: TEdge): TEdge {
  for (;;) {
    while (!ptEq(E.Bot, E.Prev.Bot) || ptEq(E.Curr, E.Top)) E = E.Next;
    if (!isHorizontal(E) && !isHorizontal(E.Prev)) break;
    while (isHorizontal(E.Prev)) E = E.Prev;
    const E2 = E;
    while (isHorizontal(E)) E = E.Next;
    if (E.Top.Y === E.Prev.Bot.Y) continue; // ie just an intermediate horz.
    if (E2.Prev.Bot.X < E.Bot.X) E = E2;
    break;
  }
  return E;
}

