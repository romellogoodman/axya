/** A pyclipper path: a list of [x, y] integer pairs. */
export type PyPath = number[][];

/** Python's OverflowError, as pyclipper's scale_to_clipper raises it. */
export class PyOverflowError extends RangeError {
  constructor(message: string) {
    super(message);
    this.name = "OverflowError";
  }
}

/** Python's ValueError. */
export class PyValueError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "ValueError";
  }
}

/**
 * <cInt>(<double>x * scale) as Cython compiles it with a Python-int scale:
 * the product is a Python float, converted to long long through int(), so
 * it truncates and raises instead of wrapping.
 */
function toCInt(x: number): number {
  const v = x * 2 ** 31;
  if (Number.isNaN(v))
    throw new PyValueError("cannot convert float NaN to integer");
  if (!Number.isFinite(v))
    throw new PyOverflowError("cannot convert float infinity to integer");
  const t = Math.trunc(v) + 0;
  if (t >= 2 ** 63 || t < -(2 ** 63))
    throw new PyOverflowError("Python int too large to convert to C long");
  return t;
}

/** scale_to_clipper(path_or_paths), scale 2**31. */
export function scaleToClipper(paths: number[][][]): PyPath[] {
  return paths.map((p) => p.map((v) => v.map(toCInt)));
}

/** scale_from_clipper: <double>x / 2**31. */
export function scaleFromClipper(paths: PyPath[]): number[][][] {
  return paths.map((p) => p.map((v) => v.map((x) => x / 2 ** 31)));
}

function toClipperPath(path: PyPath): IntPoint[] {
  return path.map((v) => pt(v[0], v[1]));
}

function fromClipperPath(path: IntPoint[]): PyPath {
  return path.map((p) => [p.X, p.Y]);
}

/** pyclipper.Pyclipper, restricted to what clipping.py calls. */
export class Pyclipper {
  private readonly c = new Clipper();

  /** AddPaths: raises ClipperException when no path was valid. */
  AddPaths(paths: PyPath[], polyType: number, closed = true): boolean {
    // An open clip path makes C++ throw through Cython, which aborts the
    // process; clipping.py always adds clip paths as closed.
    const result = this.c.AddPaths(paths.map(toClipperPath), polyType, closed);
    if (!result)
      throw new ClipperException("All paths are invalid for clipping");
    return result;
  }

  /**
   * Execute2 followed by PolyTreeToPaths: every non-empty contour of the
   * solution tree, depth first.
   */
  execute2Paths(
    clipType: number,
    subjFillType: number,
    clipFillType: number
  ): PyPath[] {
    const tree = new PolyTree();
    if (!this.c.Execute(clipType, tree, subjFillType, clipFillType))
      throw new ClipperException("Execution of clipper did not succeed!");
    const out: PyPath[] = [];
    const walk = (node: PolyNode): void => {
      if (node.Contour.length > 0) out.push(fromClipperPath(node.Contour));
      for (const child of node.Childs) walk(child);
    };
    walk(tree);
    return out;
  }
}

/** pyclipper.CleanPolygon(poly, distance=1.415) */
export function cleanPolygon(poly: PyPath, distance = 1.415): PyPath {
  return fromClipperPath(CleanPolygon(toClipperPath(poly), distance));
}
